def classify_post(post):
    """تصنيف تدوينة واحدة - الأولوية للدول العالمية على السعودية"""
    title = post.get("title", "")
    labels_list = post.get("labels", [])
    labels_text = " ".join(labels_list) if labels_list else ""
    content = post.get("content_text", "")[:800]

    # تنظيف النص من عبارات الكاتب المتكررة
    raw_search = f"{title} {labels_text} {content}"
    search_text = clean_search_text(raw_search)
    title_clean = clean_search_text(title)
    labels_clean = clean_search_text(labels_text)

    found_country = None
    found_continent = None

    # === المرحلة 1: البحث عن مدن عالمية في العنوان والتصنيفات (أعلى دقة) ===
    title_labels = f"{title_clean} {labels_clean}"
    for city, country in INTL_CITIES.items():
        if city in title_labels:
            normalized = COUNTRY_NORMALIZE.get(country, country)
            continent = COUNTRIES.get(country, None)
            if continent:
                found_country = normalized
                found_continent = continent
                break

    # === المرحلة 2: البحث عن دول عالمية في العنوان والتصنيفات ===
    if not found_country:
        for country_name, continent in INTL_COUNTRIES.items():
            if country_name in title_labels:
                # فلتر "مالي"
                if country_name == "مالي":
                    if "الدوغون" in raw_search or "باندياغارا" in raw_search or "افريقية" in raw_search or "مالي " in title_clean:
                        pass
                    else:
                        continue
                # فلتر "أمريكا"
                if country_name in ("أمريكا", "امريكا", "امريكية", "أمريكية"):
                    if "ولاية امريكية" not in raw_search and "لولاية امريكية" not in raw_search and "لولاية أمريكية" not in raw_search and "الامريكيتين" not in raw_search and ".أمريكا" not in raw_search and "أمريكا." not in raw_search:
                        continue
                # فلتر "عمان" (ممكن تكون سلطنة عمان أو مدينة في الأردن)
                if country_name == "عمان" and "سلطنة" not in raw_search and "العمانية" not in raw_search and "ظفار" not in raw_search and "كمزار" not in raw_search:
                    continue

                normalized = COUNTRY_NORMALIZE.get(country_name, country_name)
                found_country = normalized
                found_continent = continent
                break

    # === المرحلة 3: البحث أعمق في المحتوى عن مدن/دول عالمية ===
    if not found_country:
        for city, country in INTL_CITIES.items():
            if city in search_text:
                normalized = COUNTRY_NORMALIZE.get(country, country)
                continent = COUNTRIES.get(country, None)
                if continent:
                    found_country = normalized
                    found_continent = continent
                    break

    if not found_country:
        for country_name, continent in INTL_COUNTRIES.items():
            if country_name in search_text:
                if country_name == "مالي":
                    if not ("الدوغون" in search_text or "باندياغارا" in search_text or "افريقية" in search_text):
                        continue
                if country_name in ("أمريكا", "امريكا"):
                    continue
                if country_name == "عمان" and "سلطنة" not in search_text:
                    continue
                normalized = COUNTRY_NORMALIZE.get(country_name, country_name)
                found_country = normalized
                found_continent = continent
                break

    # === المرحلة 4: تحقق من التصنيفات "أخرى" قبل السعودية ===
    if not found_country:
        for category, keywords in OTHER_KEYWORDS.items():
            for kw in keywords:
                if kw in title or kw in labels_text:
                    return {
                        "continent": None,
                        "country": None,
                        "type": "other",
                        "category": category
                    }

    # === المرحلة 5: البحث عن مدن شرق أوسطية (غير سعودية) ===
    if not found_country:
        for city, country in ME_CITIES_NON_SAUDI.items():
            if city in search_text:
                normalized = COUNTRY_NORMALIZE.get(country, country)
                continent = COUNTRIES.get(country, "الشرق الأوسط")
                found_country = normalized
                found_continent = continent
                break

    # === المرحلة 6: البحث عن دول شرق أوسطية (غير سعودية) في العنوان ===
    if not found_country:
        me_countries = ["البحرين", "قطر", "الكويت", "اليمن", "العراق", "الأردن", "الاردن"]
        for c in me_countries:
            if c in title_clean:
                normalized = COUNTRY_NORMALIZE.get(c, c)
                found_country = normalized
                found_continent = "الشرق الأوسط"
                break

    # === المرحلة 7: البحث عن مدن سعودية ===
    if not found_country:
        for city in SAUDI_CITIES:
            if city in title_clean or city in labels_clean:
                found_country = "السعودية"
                found_continent = "الشرق الأوسط"
                break

    # === المرحلة 8: بحث موسع في المحتوى الكامل ===
    if not found_country:
        extended = post.get("content_text", "")[:3000]
        extended_clean = clean_search_text(extended)

        for city, country in INTL_CITIES.items():
            if city in extended_clean:
                normalized = COUNTRY_NORMALIZE.get(country, country)
                continent = COUNTRIES.get(country, None)
                if continent:
                    found_country = normalized
                    found_continent = continent
                    break

    if found_country:
        return {
            "continent": found_continent,
            "country": found_country,
            "type": "travel"
        }

    # لم نجد شيء → أخرى / عام
    return {
        "continent": None,
        "country": None,
        "type": "other",
        "category": "عام"
    }


def main():
    posts_dir = Path(__file__).parent.parent / "src" / "content" / "posts"
    output_dir = Path(__file__).parent.parent / "src" / "data"
    output_dir.mkdir(parents=True, exist_ok=True)

    print(f"📂 قراءة التدوينات من: {posts_dir}")

    taxonomy = {
        "posts": {},
        "continents": CONTINENTS_META,
        "countries": {}
    }

    stats = {
        "total": 0,
        "travel": 0,
        "other": 0,
        "by_continent": {},
        "by_country": {},
        "by_category": {},
    }

    post_files = sorted(posts_dir.glob("*.json"))
    print(f"📊 عدد التدوينات: {len(post_files)}")

    for pf in post_files:
        with open(pf, "r", encoding="utf-8") as f:
            post = json.load(f)

        slug = get_post_slug(post)
        result = classify_post(post)
        taxonomy["posts"][slug] = result
        stats["total"] += 1

        if result["type"] == "travel":
            stats["travel"] += 1
            continent = result["continent"]
            country = result["country"]
            stats["by_continent"][continent] = stats["by_continent"].get(continent, 0) + 1
            stats["by_country"][country] = stats["by_country"].get(country, 0) + 1

            # إضافة الدولة لقاموس الدول
            if country not in taxonomy["countries"]:
                taxonomy["countries"][country] = {
                    "slug": make_slug(country),
                    "continent": continent
                }
        else:
            stats["other"] += 1
            cat = result.get("category", "عام")
            stats["by_category"][cat] = stats["by_category"].get(cat, 0) + 1

    # حفظ taxonomy.json
    output_file = output_dir / "taxonomy.json"
    with open(output_file, "w", encoding="utf-8") as f:
        json.dump(taxonomy, f, ensure_ascii=False, indent=2)

    print(f"\n✅ تم حفظ التصنيف في: {output_file}")
    print(f"\n{'='*50}")
    print(f"📊 الإحصائيات:")
    print(f"  إجمالي التدوينات: {stats['total']}")
    print(f"  تدوينات رحلات: {stats['travel']}")
    print(f"  تدوينات أخرى: {stats['other']}")

    print(f"\n🌍 حسب القارة:")
    for continent, count in sorted(stats["by_continent"].items(), key=lambda x: -x[1]):
        print(f"  {continent}: {count}")

    print(f"\n🏳️ حسب الدولة:")
    for country, count in sorted(stats["by_country"].items(), key=lambda x: -x[1]):
        print(f"  {country}: {count}")

    print(f"\n📁 التصنيفات الأخرى:")
    for cat, count in sorted(stats["by_category"].items(), key=lambda x: -x[1]):
        print(f"  {cat}: {count}")

    # طباعة التدوينات غير المصنفة للمراجعة
    print(f"\n{'='*50}")
    print("📋 التدوينات المصنفة كـ 'أخرى / عام' (للمراجعة):")
    for pf in post_files:
        with open(pf, "r", encoding="utf-8") as f:
            post = json.load(f)
        slug = get_post_slug(post)
        if taxonomy["posts"][slug].get("category") == "عام":
            print(f"  ❓ {post['title'][:80]}")


if __name__ == "__main__":
    main()
