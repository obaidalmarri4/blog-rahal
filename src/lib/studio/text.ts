/**
 * مفتاح البحث في العناوين: يوحّد ما يكتبه الناس بأشكال مختلفة، فيجد «الاحساء» تدوينة
 * «الأحساء» و«رحله» تدوينة «رحلة». يُستعمل في الخادم (عند عرض القائمة) وفي المتصفح (عند
 * الكتابة في خانة البحث) — ويجب أن يبقى واحداً فيهما.
 */
export function searchKey(value: string): string {
  return value
    .toLowerCase()
    .replace(/[ً-ٰٟـ]/g, '') // التشكيل والتطويل
    .replace(/[أإآٱ]/g, 'ا')
    .replace(/ة/g, 'ه')
    .replace(/ى/g, 'ي')
    .replace(/ؤ/g, 'و')
    .replace(/ئ/g, 'ي')
    .replace(/\s+/g, ' ')
    .trim();
}
